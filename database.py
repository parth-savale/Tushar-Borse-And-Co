def _record(row):
    return SimpleNamespace(**row) if row is not None else None


def fetch_one(sql, params=()):
    _ensure_pool_open()
    with pool.connection() as connection:
        return _record(connection.execute(sql, params).fetchone())


def fetch_all(sql, params=()):
    _ensure_pool_open()
    with pool.connection() as connection:
        return [_record(row) for row in connection.execute(sql, params).fetchall()]


def execute(sql, params=()):
    _ensure_pool_open()
    with pool.connection() as connection:
        cursor = connection.execute(sql, params)
        row = cursor.fetchone() if cursor.description else None
        return _record(row)


@contextmanager
def transaction():
    _ensure_pool_open()
    with pool.connection() as connection:
        with connection.transaction():
            yield connection


def initialize_schema():
    """Create all application tables/indexes atomically; safe to rerun."""
    _ensure_pool_open()
    with transaction() as connection:
        for statement in SCHEMA_DDL:
            connection.execute(statement)


def health_check():
    return fetch_one("SELECT 1 AS healthy").healthy == 1


def close_pool():
    pool.close()
